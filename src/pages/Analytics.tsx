import { useEffect, useState, useCallback } from 'react';
import { BarChart3, Gauge, Cpu, MemoryStick, Clock, Zap } from 'lucide-react';
import { supabase } from '../lib/supabase';
import { TopBar, LoadingSpinner, EmptyState } from '../components/Layout';
import type { PerformanceReport, PerfCategory, Project } from '../lib/types';
import type { LucideIcon } from 'lucide-react';

const categoryInfo: Record<PerfCategory, { icon: LucideIcon; color: string; bg: string; label: string; barColor: string }> = {
  cpu: { icon: Cpu, color: 'text-[var(--sky)]', bg: 'bg-[var(--sky)]/10', label: 'CPU', barColor: 'var(--sky)' },
  memory: { icon: MemoryStick, color: 'text-[var(--emerald)]', bg: 'bg-[var(--emerald)]/10', label: 'Memory', barColor: 'var(--emerald)' },
  latency: { icon: Clock, color: 'text-[var(--amber)]', bg: 'bg-[var(--amber)]/10', label: 'Latency', barColor: 'var(--amber)' },
  throughput: { icon: Zap, color: 'text-[var(--violet)]', bg: 'bg-[var(--violet)]/10', label: 'Throughput', barColor: 'var(--violet)' },
};

export function AnalyticsPage() {
  const [reports, setReports] = useState<PerformanceReport[]>([]);
  const [projects, setProjects] = useState<Project[]>([]);
  const [loading, setLoading] = useState(true);

  const load = useCallback(async () => {
    const [{ data: perf }, { data: projs }] = await Promise.all([
      supabase.from('performance_reports').select('*').order('created_at', { ascending: false }),
      supabase.from('projects').select('*').order('created_at', { ascending: false }),
    ]);
    setReports((perf || []) as PerformanceReport[]);
    setProjects((projs || []) as Project[]);
    setLoading(false);
  }, []);

  useEffect(() => {
    load();
    const ch = supabase.channel('analytics-realtime')
      .on('postgres_changes', { event: '*', schema: 'public', table: 'performance_reports' }, load)
      .on('postgres_changes', { event: '*', schema: 'public', table: 'projects' }, load)
      .subscribe();
    const interval = setInterval(load, 8000);
    return () => { supabase.removeChannel(ch); clearInterval(interval); };
  }, [load]);

  if (loading) return <><TopBar title="Analytics" /><LoadingSpinner label="Loading..." /></>;
  if (reports.length === 0 && projects.length === 0) {
    return (
      <>
        <TopBar title="Analytics" subtitle="Performance metrics and platform insights" />
        <EmptyState icon={BarChart3} title="No analytics data" message="Performance metrics are generated by the Performance agent after each project runs. Create a project to see data here." />
      </>
    );
  }

  const byCategory: Record<PerfCategory, PerformanceReport[]> = { cpu: [], memory: [], latency: [], throughput: [] };
  reports.forEach((r) => byCategory[r.category].push(r));

  const statusCounts = {
    completed: projects.filter(p => p.status === 'completed').length,
    failed: projects.filter(p => p.status === 'failed').length,
    inProgress: projects.filter(p => ['analyzing', 'generating', 'executing', 'healing'].includes(p.status)).length,
    drafting: projects.filter(p => p.status === 'drafting').length,
  };

  const total = projects.length || 1;

  // Find max value per category for bar scaling
  const maxByCat: Record<string, number> = {};
  (Object.keys(byCategory) as PerfCategory[]).forEach((cat) => {
    maxByCat[cat] = Math.max(...byCategory[cat].map((r) => r.metric_value), 1);
  });

  return (
    <>
      <TopBar
        title="Analytics"
        subtitle="Performance metrics and platform insights"
        actions={
          <span className="text-[10px] text-[var(--text-mute)] flex items-center gap-1">
            <span className="w-1.5 h-1.5 rounded-full bg-[var(--emerald)] pulse-dot" /> Live
          </span>
        }
      />
      <div className="flex-1 overflow-y-auto p-6 space-y-4 fade-in">
        {/* Platform overview */}
        <div className="panel p-4">
          <h3 className="text-[12.5px] font-semibold text-[var(--text)] mb-3">Platform Overview</h3>
          <div className="grid grid-cols-4 gap-2.5">
            <PlatformStat label="Completed" value={statusCounts.completed} color="text-[var(--emerald)]" bg="bg-[var(--emerald)]/10" />
            <PlatformStat label="In Progress" value={statusCounts.inProgress} color="text-[var(--sky)]" bg="bg-[var(--sky)]/10" />
            <PlatformStat label="Failed" value={statusCounts.failed} color="text-[var(--rose)]" bg="bg-[var(--rose)]/10" />
            <PlatformStat label="Drafting" value={statusCounts.drafting} color="text-[var(--text-dim)]" bg="bg-[var(--panel-3)]" />
          </div>
          {projects.length > 0 && (
            <div className="mt-3.5">
              <div className="flex h-1.5 rounded-full overflow-hidden bg-[var(--bg-elevated)] border border-[var(--border)]">
                {statusCounts.completed > 0 && <div className="bg-[var(--emerald)] transition-all duration-700" style={{ width: `${(statusCounts.completed / total) * 100}%` }} />}
                {statusCounts.inProgress > 0 && <div className="bg-[var(--sky)] transition-all duration-700" style={{ width: `${(statusCounts.inProgress / total) * 100}%` }} />}
                {statusCounts.failed > 0 && <div className="bg-[var(--rose)] transition-all duration-700" style={{ width: `${(statusCounts.failed / total) * 100}%` }} />}
                {statusCounts.drafting > 0 && <div className="bg-[var(--text-mute)] transition-all duration-700" style={{ width: `${(statusCounts.drafting / total) * 100}%` }} />}
              </div>
              <div className="flex items-center gap-3 mt-2 text-[9.5px] text-[var(--text-mute)]">
                <span className="flex items-center gap-1"><span className="w-1.5 h-1.5 rounded-full bg-[var(--emerald)]" /> Completed</span>
                <span className="flex items-center gap-1"><span className="w-1.5 h-1.5 rounded-full bg-[var(--sky)]" /> In Progress</span>
                <span className="flex items-center gap-1"><span className="w-1.5 h-1.5 rounded-full bg-[var(--rose)]" /> Failed</span>
                <span className="flex items-center gap-1"><span className="w-1.5 h-1.5 rounded-full bg-[var(--text-mute)]" /> Drafting</span>
              </div>
            </div>
          )}
        </div>

        {/* Performance metrics by category — with animated bars */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
          {(Object.keys(byCategory) as PerfCategory[]).map((cat) => {
            const info = categoryInfo[cat];
            const Icon = info.icon;
            const items = byCategory[cat];
            const max = maxByCat[cat];
            return (
              <div key={cat} className="panel p-4">
                <div className="flex items-center gap-2 mb-3">
                  <div className={`w-7 h-7 rounded-[6px] flex items-center justify-center ${info.bg}`}>
                    <Icon size={14} className={info.color} />
                  </div>
                  <h3 className="text-[12px] font-semibold text-[var(--text)]">{info.label}</h3>
                  <span className="text-[9.5px] text-[var(--text-mute)] ml-auto">{items.length} points</span>
                </div>
                {items.length === 0 ? (
                  <p className="text-[11px] text-[var(--text-mute)] py-4 text-center">No data yet</p>
                ) : (
                  <div className="space-y-2">
                    {items.slice(0, 6).map((r) => {
                      const pct = Math.round((r.metric_value / max) * 100);
                      return (
                        <div key={r.id} className="panel-2 p-2.5 panel-hover">
                          <div className="flex items-center justify-between mb-1">
                            <p className="text-[11px] font-medium text-[var(--text)]">{r.metric_name}</p>
                            <p className={`text-[13px] font-bold ${info.color}`}>{r.metric_value}<span className="text-[9px] text-[var(--text-mute)] ml-1 font-normal">{r.unit}</span></p>
                          </div>
                          {/* Animated bar */}
                          <div className="h-1 rounded-full bg-[var(--bg-elevated)] overflow-hidden mt-1.5">
                            <div
                              className="h-full rounded-full progress-fill transition-all duration-700"
                              style={{ width: `${pct}%`, background: info.barColor }}
                            />
                          </div>
                          {r.recommendation && <p className="text-[10px] text-[var(--text-mute)] mt-1.5 leading-relaxed">{r.recommendation}</p>}
                        </div>
                      );
                    })}
                  </div>
                )}
              </div>
            );
          })}
        </div>

        {/* Full metrics table */}
        {reports.length > 0 && (
          <div className="panel p-4">
            <h3 className="text-[12.5px] font-semibold text-[var(--text)] mb-3">All Performance Reports</h3>
            <div className="overflow-x-auto">
              <table className="w-full text-[11.5px]">
                <thead>
                  <tr className="text-left text-[9.5px] uppercase tracking-[0.06em] text-[var(--text-mute)] font-medium border-b border-[var(--border)]">
                    <th className="py-2.5 pr-4">Metric</th>
                    <th className="py-2.5 pr-4">Category</th>
                    <th className="py-2.5 pr-4">Value</th>
                    <th className="py-2.5 pr-4">Recommendation</th>
                  </tr>
                </thead>
                <tbody>
                  {reports.map((r) => (
                    <tr key={r.id} className="border-b border-[var(--border)]/30 last:border-0 hover:bg-[var(--panel-2)]/30 transition-colors">
                      <td className="py-2.5 pr-4 font-medium text-[var(--text)]">{r.metric_name}</td>
                      <td className="py-2.5 pr-4 text-[var(--text-mute)] capitalize">{r.category}</td>
                      <td className="py-2.5 pr-4 font-semibold text-[var(--text)]">{r.metric_value} <span className="text-[var(--text-mute)] font-normal">{r.unit}</span></td>
                      <td className="py-2.5 pr-4 text-[var(--text-dim)] max-w-xs truncate">{r.recommendation}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        )}
      </div>
    </>
  );
}

function PlatformStat({ label, value, color, bg }: { label: string; value: number; color: string; bg: string }) {
  return (
    <div className="panel-2 p-3">
      <div className={`w-6 h-6 rounded-[5px] flex items-center justify-center mb-2 ${bg} ${color}`}>
        <Gauge size={13} />
      </div>
      <p className={`text-[18px] font-bold ${color} leading-none`}>{value}</p>
      <p className="text-[9.5px] uppercase tracking-[0.06em] text-[var(--text-mute)] mt-1 font-medium">{label}</p>
    </div>
  );
}
